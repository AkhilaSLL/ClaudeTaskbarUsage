# Extracts the Claude spark from the 256 px app icon of the installed Claude desktop app as an 8-bit
# alpha mask and writes it as a C header (src\logo_mask.h). Read only on the source; deterministic:
# the same input gives the same bytes.
#
# Usage: py -3 -I tools\logo_mask.py <icon.png> <out.h> [<source label>]
#   icon.png: Square44x44Logo.targetsize-256_altform-unplated.png of the Claude package
#             (C:\Program Files\WindowsApps\Claude_<version>_x64__pzs8sxrjxfjjc\assets\)
#
# Method: the icon is an orange rounded tile (a vertical gradient, #D97756 at the top) with the spark in
# near-white. Per row, the background "R - B" value is the median of the clearly orange pixels of that
# row. The spark coverage of a pixel is how far its "R - B" moved from that background towards the
# spark interior (R - B <= SPARK_D, the spark has a slight warm tint), clamped to 0..1 and multiplied by
# the icon alpha. The mask is cropped to a square around the spark (centred on its bounding box).
# The fill colour is the median colour of the background pixels of the top quarter of the tile.
import hashlib
import os
import sys

from PIL import Image

SPARK_D = 28      # R - B of the spark interior (white to light pink) and below: full coverage
BG_MIN_D = 100    # R - B above this: background pixel (used for the background estimate)
MARGIN = 1        # empty pixels around the spark in the crop
NOISE = 8         # coverage below this (of 255) is background noise


def median(vals):
    vals = sorted(vals)
    return vals[len(vals) // 2]


def main():
    if len(sys.argv) < 3:
        print("usage: logo_mask.py <icon.png> <out.h> [<source label>]")
        return 2
    src, out = sys.argv[1], sys.argv[2]
    label = sys.argv[3] if len(sys.argv) > 3 else os.path.basename(src)
    raw = open(src, "rb").read()
    sha = hashlib.sha256(raw).hexdigest().upper()
    im = Image.open(src).convert("RGBA")
    w, h = im.size
    px = im.load()

    # Background R - B per row (gradient), from the clearly orange opaque pixels.
    bg_d = []
    last = None
    for y in range(h):
        ds = [px[x, y][0] - px[x, y][2] for x in range(w) if px[x, y][3] == 255 and px[x, y][0] - px[x, y][2] > BG_MIN_D]
        if ds:
            last = median(ds)
        bg_d.append(last)
    first = next(v for v in bg_d if v is not None)
    bg_d = [v if v is not None else first for v in bg_d]

    cov = [[0] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            if a < 255:
                continue  # the tile's own anti-aliased rim: never spark
            d = r - b
            span = bg_d[y] - SPARK_D
            c = (bg_d[y] - d) / span if span > 0 else 0.0
            c = max(0.0, min(1.0, c))
            v = int(c * 255 + 0.5)
            cov[y][x] = v if v >= NOISE else 0  # the background gradient has a little dither noise

    xs = [x for y in range(h) for x in range(w) if cov[y][x] > 0]
    ys = [y for y in range(h) for x in range(w) if cov[y][x] > 0]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    size = max(x1 - x0 + 1, y1 - y0 + 1) + 2 * MARGIN
    cx2, cy2 = x0 + x1 + 1, y0 + y1 + 1          # twice the centre
    ox, oy = (cx2 - size) // 2, (cy2 - size) // 2
    mask = []
    for y in range(oy, oy + size):
        for x in range(ox, ox + size):
            mask.append(cov[y][x] if 0 <= x < w and 0 <= y < h else 0)

    # Fill colour: median of the background of the top quarter of the tile.
    rs, gs, bs = [], [], []
    for y in range(h // 4):
        for x in range(w):
            r, g, b, a = px[x, y]
            if a == 255 and r - b > BG_MIN_D:
                rs.append(r)
                gs.append(g)
                bs.append(b)
    col = (median(rs), median(gs), median(bs))

    lines = []
    lines.append("/* Generated by tools\\logo_mask.py. Do not edit by hand. */")
    lines.append("/* Source: %s */" % label)
    lines.append("/* Source SHA-256: %s (%d x %d) */" % (sha, w, h))
    lines.append("/* Crop: x %d, y %d, %d px square; spark bounding box %d..%d x %d..%d */" % (ox, oy, size, x0, x1, y0, y1))
    lines.append("#ifndef CTU_LOGO_MASK_H")
    lines.append("#define CTU_LOGO_MASK_H")
    lines.append("#define CTU_LOGO_N %d" % size)
    lines.append("#define CTU_LOGO_R 0x%02X" % col[0])
    lines.append("#define CTU_LOGO_G 0x%02X" % col[1])
    lines.append("#define CTU_LOGO_B 0x%02X" % col[2])
    lines.append("static const unsigned char ctu_logo_data[CTU_LOGO_N * CTU_LOGO_N] = {")
    for i in range(0, len(mask), 24):
        lines.append("    " + ",".join(str(v) for v in mask[i:i + 24]) + ",")
    lines.append("};")
    lines.append("#endif")
    data = ("\r\n".join(lines) + "\r\n").encode("ascii")
    with open(out, "wb") as f:
        f.write(data)
    print("mask %d x %d, colour #%02X%02X%02X, source sha256 %s, wrote %s (%d bytes, sha256 %s)" % (
        size, size, col[0], col[1], col[2], sha, out, len(data), hashlib.sha256(data).hexdigest().upper()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
